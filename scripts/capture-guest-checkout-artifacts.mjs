/**
 * Capture guest-checkout fixture screenshots into artifacts/guest-checkout/.
 * Uses Puppeteer against local HTML fixtures (mocked / flag-ON UX).
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import puppeteer from "puppeteer";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "artifacts/guest-checkout");
const fixtures = path.join(outDir, "fixtures");

const shots = [
  { file: "checkout-sv.html", name: "checkout-sv-375", width: 375, height: 812 },
  { file: "checkout-sv.html", name: "checkout-sv-390", width: 390, height: 844 },
  { file: "checkout-sv.html", name: "checkout-sv-1440", width: 1440, height: 900 },
  { file: "checkout-en.html", name: "checkout-en-375", width: 375, height: 812 },
  { file: "checkout-en.html", name: "checkout-en-390", width: 390, height: 844 },
  { file: "checkout-en.html", name: "checkout-en-1440", width: 1440, height: 900 },
  {
    file: "confirmation-account-offer-sv.html",
    name: "confirmation-account-offer-sv-390",
    width: 390,
    height: 844,
  },
  {
    file: "confirmation-account-offer-en.html",
    name: "confirmation-account-offer-en-390",
    width: 390,
    height: 844,
  },
  {
    file: "confirmation-account-offer-sv.html",
    name: "confirmation-account-offer-sv-1440",
    width: 1440,
    height: 900,
  },
];

await mkdir(outDir, { recursive: true });

const browser = await puppeteer.launch({
  headless: true,
  args: ["--no-sandbox", "--disable-setuid-sandbox"],
});

try {
  for (const shot of shots) {
    const page = await browser.newPage();
    await page.setViewport({ width: shot.width, height: shot.height, deviceScaleFactor: 2 });
    const url = pathToFileURL(path.join(fixtures, shot.file)).href;
    await page.goto(url, { waitUntil: "networkidle0" });
    // Wait briefly for web fonts
    await new Promise((r) => setTimeout(r, 400));
    const dest = path.join(outDir, `${shot.name}.png`);
    await page.screenshot({ path: dest, fullPage: true });
    await page.close();
    console.log("wrote", dest);
  }
} finally {
  await browser.close();
}

const notes = `# Guest checkout screenshots

Flag ON fixtures (mocked test env). Geist font. CTA uses **Köp** / **Buy** (not reservation).

| File | Viewport | Locale | Scene |
| --- | --- | --- | --- |
| checkout-sv-375.png | 375 | SV | Mid-checkout guest path, no login wall |
| checkout-sv-390.png | 390 | SV | Mid-checkout guest path |
| checkout-sv-1440.png | 1440 | SV | Mid-checkout guest path |
| checkout-en-375.png | 375 | EN | Mid-checkout guest path |
| checkout-en-390.png | 390 | EN | Mid-checkout guest path |
| checkout-en-1440.png | 1440 | EN | Mid-checkout guest path |
| confirmation-account-offer-sv-390.png | 390 | SV | Optional account offer; consent unchecked |
| confirmation-account-offer-en-390.png | 390 | EN | Optional account offer; consent unchecked |
| confirmation-account-offer-sv-1440.png | 1440 | SV | Optional account offer |

Generated by \`scripts/capture-guest-checkout-artifacts.mjs\`.
`;

await writeFile(path.join(outDir, "notes.md"), notes);
console.log("wrote notes.md");
